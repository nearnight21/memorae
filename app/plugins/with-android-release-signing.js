const { withAppBuildGradle } = require('expo/config-plugins');

const CONFIG_MARKER = '// @generated by with-android-release-signing';

function findBlockClosingBrace(contents, blockName) {
  const blockPattern = new RegExp(`${blockName}\\s*\\{`);
  const match = blockPattern.exec(contents);
  if (!match) return -1;

  let depth = 1;
  const openingBrace = match.index + match[0].lastIndexOf('{');
  for (let index = openingBrace + 1; index < contents.length; index += 1) {
    if (contents[index] === '{') depth += 1;
    if (contents[index] === '}') depth -= 1;
    if (depth === 0) return index;
  }
  return -1;
}

function patchReleaseSigning(contents) {
  if (contents.includes(CONFIG_MARKER)) return contents;

  const projectRootPattern = /(def projectRoot = .*\r?\n)/;
  if (!projectRootPattern.test(contents)) {
    throw new Error('无法定位 Android app/build.gradle 的 projectRoot。');
  }

  const signingEnvironment = `${CONFIG_MARKER}
def memoryRecallReleaseKeystore = System.getenv("MEMORY_RECALL_ANDROID_KEYSTORE_PATH")
def memoryRecallReleaseStorePassword = System.getenv("MEMORY_RECALL_ANDROID_STORE_PASSWORD")
def memoryRecallReleaseKeyAlias = System.getenv("MEMORY_RECALL_ANDROID_KEY_ALIAS")
def memoryRecallReleaseKeyPassword = System.getenv("MEMORY_RECALL_ANDROID_KEY_PASSWORD")
def memoryRecallReleaseSigningConfigured = [
    memoryRecallReleaseKeystore,
    memoryRecallReleaseStorePassword,
    memoryRecallReleaseKeyAlias,
    memoryRecallReleaseKeyPassword,
].every { it != null && !it.trim().isEmpty() }
def memoryRecallReleaseRequested = gradle.startParameter.taskNames.any {
    it.toLowerCase().contains("release")
}
if (memoryRecallReleaseRequested && !memoryRecallReleaseSigningConfigured) {
    throw new GradleException("Release 构建必须配置所忆唯一正式签名的四个 MEMORY_RECALL_ANDROID_* 环境变量。")
}
`;
  let patched = contents.replace(
    projectRootPattern,
    `$1\n${signingEnvironment}\n`,
  );

  const signingConfigsPattern = /(signingConfigs\s*\{\s*\r?\n)/;
  if (!signingConfigsPattern.test(patched)) {
    throw new Error('无法定位 Android app/build.gradle 的 signingConfigs。');
  }
  patched = patched.replace(
    signingConfigsPattern,
    `$1        if (memoryRecallReleaseSigningConfigured) {
            release {
                storeFile file(memoryRecallReleaseKeystore)
                storePassword memoryRecallReleaseStorePassword
                keyAlias memoryRecallReleaseKeyAlias
                keyPassword memoryRecallReleaseKeyPassword
                storeType "PKCS12"
            }
        }
`,
  );

  // Anchor the replacement inside buildTypes.release. A loose `release { ... }`
  // match can start at signingConfigs.release and accidentally rewrite the
  // debug build type instead of the release build type.
  const releaseDebugSigningPattern = /(buildTypes\s*\{[\s\S]*?\brelease\s*\{[\s\S]*?)signingConfig signingConfigs\.debug/;
  if (!releaseDebugSigningPattern.test(patched)) {
    throw new Error('无法定位 Android release 的临时 debug 签名。');
  }
  patched = patched.replace(
    releaseDebugSigningPattern,
    '$1signingConfig memoryRecallReleaseSigningConfigured ? signingConfigs.release : signingConfigs.debug',
  );

  if (!patched.includes('standalone {')) {
    const buildTypesEnd = findBlockClosingBrace(patched, 'buildTypes');
    if (buildTypesEnd < 0) {
      throw new Error('无法定位 Android buildTypes 的结束位置。');
    }
    const standaloneBuildType = `
        // Standalone device验收包：内嵌 JS bundle、关闭 Metro 依赖，但沿用 debug 签名
        // 以便覆盖本地开发安装而不清除设备上的测试数据。正式 release 仍要求正式签名。
        standalone {
            initWith release
            signingConfig signingConfigs.debug
            debuggable false
            matchingFallbacks = ['release']
        }
`;
    patched = `${patched.slice(0, buildTypesEnd)}${standaloneBuildType}${patched.slice(buildTypesEnd)}`;
  }

  return patched;
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error('所忆 Android release 签名插件只支持 Groovy build.gradle。');
    }
    gradleConfig.modResults.contents = patchReleaseSigning(
      gradleConfig.modResults.contents,
    );
    return gradleConfig;
  });
};

module.exports.patchReleaseSigning = patchReleaseSigning;
