const {
  AndroidConfig,
  withAndroidManifest,
  withAppBuildGradle,
  withGradleProperties,
} = require('expo/config-plugins');

const AMAP_KEY_META_DATA = 'com.amap.api.v2.apikey';
const ACCESS_NETWORK_STATE_PERMISSION = 'android.permission.ACCESS_NETWORK_STATE';
const MISSING_KEY_SENTINEL = 'AMAP_KEY_NOT_CONFIGURED';

module.exports = function withAmapMap(config, props = {}) {
  const envName = props.apiKeyEnv ?? 'MEMORY_RECALL_AMAP_ANDROID_KEY';
  const apiKey = process.env[envName]?.trim() || MISSING_KEY_SENTINEL;

  const manifestConfig = withAndroidManifest(config, (nextConfig) => {
    const permissions = nextConfig.modResults.manifest['uses-permission'] ?? [];
    const withoutDuplicateNetworkPermission = permissions.filter(
      (entry) => entry.$?.['android:name'] !== ACCESS_NETWORK_STATE_PERMISSION,
    );
    nextConfig.modResults.manifest['uses-permission'] = [
      ...withoutDuplicateNetworkPermission,
      { $: { 'android:name': ACCESS_NETWORK_STATE_PERMISSION } },
    ];

    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      nextConfig.modResults,
    );
    const metadata = application['meta-data'] ?? [];
    const withoutOldKey = metadata.filter(
      (entry) => entry.$?.['android:name'] !== AMAP_KEY_META_DATA,
    );
    application['meta-data'] = [
      ...withoutOldKey,
      {
        $: {
          'android:name': AMAP_KEY_META_DATA,
          'android:value': apiKey,
        },
      },
    ];
    return nextConfig;
  });

  const appBuildGradleConfig = withAppBuildGradle(manifestConfig, (gradleConfig) => {
    const marker = '// @generated by with-amap-map: ARM-only AMap 10.x';
    if (!gradleConfig.modResults.contents.includes(marker)) {
      const defaultConfigPattern = /(defaultConfig\s*\{\s*\r?\n)/;
      if (!defaultConfigPattern.test(gradleConfig.modResults.contents)) {
        throw new Error('无法定位 Android app/build.gradle 的 defaultConfig。');
      }
      gradleConfig.modResults.contents = gradleConfig.modResults.contents.replace(
        defaultConfigPattern,
        `$1        ${marker}\n        ndk { abiFilters "armeabi-v7a", "arm64-v8a" }\n`,
      );
    }
    return gradleConfig;
  });

  return withGradleProperties(appBuildGradleConfig, (propertiesConfig) => {
    propertiesConfig.modResults = propertiesConfig.modResults.filter(
      (entry) => entry.type !== 'property' || entry.key !== 'reactNativeArchitectures',
    );
    propertiesConfig.modResults.push({
      type: 'property',
      key: 'reactNativeArchitectures',
      value: 'armeabi-v7a,arm64-v8a',
    });
    return propertiesConfig;
  });
};
