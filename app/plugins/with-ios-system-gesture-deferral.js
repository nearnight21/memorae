const { withAppDelegate } = require('expo/config-plugins');

const GENERATED_MARKER = '// @generated by with-ios-system-gesture-deferral';
const ROOT_CONTROLLER = 'MemoraeRootViewController';

const SWIFT_CONTROLLER = `${GENERATED_MARKER}
final class ${ROOT_CONTROLLER}: UIViewController {
  override var preferredScreenEdgesDeferringSystemGestures: UIRectEdge {
    return [.bottom]
  }
}
`;

const SWIFT_ROOT_CONTROLLER_FACTORY = `
  override func createRootViewController() -> UIViewController {
    return ${ROOT_CONTROLLER}()
  }
`;

function patchSwiftAppDelegate(contents) {
  if (contents.includes(GENERATED_MARKER)) return contents;

  const delegatePattern = /(class ReactNativeDelegate:\s*ExpoReactNativeFactoryDelegate\s*\{)/;
  if (!delegatePattern.test(contents)) {
    throw new Error('无法定位 iOS ReactNativeDelegate，不能配置底部系统手势优先级。');
  }

  const patched = contents.replace(
    delegatePattern,
    `$1${SWIFT_ROOT_CONTROLLER_FACTORY}`,
  );
  return `${patched.trimEnd()}\n\n${SWIFT_CONTROLLER}`;
}

function patchIosSystemGestureDeferral(contents, language = 'swift') {
  if (language !== 'swift') {
    throw new Error('所忆 iOS 系统手势插件只支持 Swift AppDelegate。');
  }
  return patchSwiftAppDelegate(contents);
}

module.exports = function withIosSystemGestureDeferral(config) {
  return withAppDelegate(config, (appDelegateConfig) => {
    appDelegateConfig.modResults.contents = patchIosSystemGestureDeferral(
      appDelegateConfig.modResults.contents,
      appDelegateConfig.modResults.language,
    );
    return appDelegateConfig;
  });
};

module.exports.patchIosSystemGestureDeferral = patchIosSystemGestureDeferral;
