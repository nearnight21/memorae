import { readFile, writeFile } from 'node:fs/promises';

const inputPath = process.argv[2];
const outputPath = process.argv[3];

if (!inputPath || !outputPath) {
  throw new Error('用法：node build-overseas-city-data.mjs <cities15000.txt> <输出.ts>');
}

const source = await readFile(inputPath, 'utf8');
const rows = [];

for (const line of source.split(/\r?\n/)) {
  if (!line) continue;
  const fields = line.split('\t');
  const id = fields[0];
  const name = fields[1];
  const latitude = Number(fields[4]);
  const longitude = Number(fields[5]);
  const featureClass = fields[6];
  const featureCode = fields[7];
  const countryCode = fields[8];
  const population = Number(fields[14]);
  if (
    !id || !name || !countryCode || !Number.isFinite(latitude)
    || !Number.isFinite(longitude) || !Number.isFinite(population)
    || featureClass !== 'P'
    || countryCode === 'CN'
    || (population < 100_000 && featureCode !== 'PPLC')
  ) continue;
  rows.push([
    id,
    name,
    Number(latitude.toFixed(5)),
    Number(longitude.toFixed(5)),
    countryCode,
    population,
    featureCode === 'PPLC' ? 1 : 0,
  ]);
}

rows.sort((left, right) => (
  right[5] - left[5]
  || String(left[4]).localeCompare(String(right[4]))
  || String(left[1]).localeCompare(String(right[1]))
  || String(left[0]).localeCompare(String(right[0]))
));

const output = [
  '// Generated by scripts/build-overseas-city-data.mjs. Do not edit by hand.',
  '// GeoNames CC BY 4.0 attribution: https://www.geonames.org/',
  `// Selected ${rows.length} non-CN cities from cities15000: population >= 100000 or PPLC.`,
  'export const OVERSEAS_CITY_TUPLES = [',
  ...rows.map((row) => `  ${JSON.stringify(row)},`),
  '] as const;',
  '',
].join('\n');

await writeFile(outputPath, output, 'utf8');
console.log(`生成 ${rows.length} 个海外城市：${outputPath}`);
